# Excel writes filled-down formulas as "shared formulas": only the first cell has the text
src = ROOT / "test" / "workbooks" / "01_correct.xlsx"
zin = zipfile.ZipFile(src); buf = io.BytesIO(); zout = zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED)
for item in zin.infolist():
    data = zin.read(item.filename)
    if item.filename == "xl/worksheets/sheet1.xml":
        x = data.decode()
        x = x.replace('<f aca="false">C4/1000*$B$2</f>', '<f t="shared" ref="D4:D18" si="0">C4/1000*$B$2</f>')
        x = re.sub(r'<f aca="false">C(\d+)/1000\*\$B\$2</f>', lambda m: '<f t="shared" si="0"/>' if m.group(1) != "4" else m.group(0), x)
        data = x.encode()
    zout.writestr(item, data)
zout.close(); (TMP / "shared.xlsx").write_bytes(buf.getvalue())

